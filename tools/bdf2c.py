#!/usr/bin/env python3
"""Convert a fixed-width BDF font (width <= 8) into a C glyph table.

Usage: bdf2c.py <font.bdf> <c_name> <out.c>

Emits glyphs for code points 32..126. Each glyph is `height` bytes, one per
row, MSB = leftmost pixel.
"""
import sys


def parse_bdf(path):
    glyphs = {}
    width = height = None
    asc = 0
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("FONTBOUNDINGBOX"):
            _, w, h, _, yoff = line.split()
            width, height = int(w), int(h)
            asc = height + int(yoff)
        elif line.startswith("STARTCHAR"):
            enc = None
            bbx = None
            rows = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                l = lines[i]
                if l.startswith("ENCODING"):
                    enc = int(l.split()[1])
                elif l.startswith("BBX"):
                    bbx = [int(v) for v in l.split()[1:]]
                elif l.startswith("BITMAP"):
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(int(lines[i], 16))
                        i += 1
                    break
                i += 1
            if enc is not None and bbx is not None:
                glyphs[enc] = (bbx, rows)
        i += 1
    return width, height, asc, glyphs


def main():
    path, name, out = sys.argv[1:4]
    width, height, asc, glyphs = parse_bdf(path)
    assert width <= 8
    data = []
    for cp in range(32, 127):
        bitmap = [0] * height
        if cp in glyphs:
            (bw, bh, bx, by), rows = glyphs[cp]
            nbytes = (bw + 7) // 8
            top = asc - (bh + by)
            for r, v in enumerate(rows):
                y = top + r
                if 0 <= y < height:
                    v8 = v >> (8 * (nbytes - 1)) if nbytes > 1 else v
                    bitmap[y] = (v8 >> bx) & 0xFF
        data.append(bitmap)
    with open(out, "w") as f:
        f.write("// Generated by tools/bdf2c.py from Spleen (BSD 2-Clause, (c) Frederic Cambus)\n")
        f.write('#include "font.h"\n\n')
        f.write(f"static const uint8_t {name}_data[] = {{\n")
        for cp, bm in zip(range(32, 127), data):
            f.write("    " + ",".join(f"0x{b:02x}" for b in bm) + f", // {chr(cp)!r}\n")
        f.write("};\n\n")
        f.write(f"const font_t {name} = {{ {width}, {height}, {name}_data }};\n")


if __name__ == "__main__":
    main()
